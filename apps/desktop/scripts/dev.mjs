import { createServer } from 'vite';
import { build } from 'esbuild';
import electron from 'electron';
import { spawn } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
process.chdir(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'));
await fs.mkdir('dist', { recursive: true });
await import('./vendor-talk.mjs');
await build({ entryPoints: ['src/main/main.ts'], bundle: true, platform: 'node', format: 'cjs', target: 'node24', outfile: 'dist/main.cjs', external: ['electron'] });
await build({ entryPoints: ['src/main/preload.ts'], bundle: true, platform: 'node', format: 'cjs', target: 'node24', outfile: 'dist/preload.cjs', external: ['electron'] });
await build({ entryPoints: ['src/main/media-preload.ts'], bundle: true, platform: 'node', format: 'cjs', target: 'node24', outfile: 'dist/media-preload.cjs', external: ['electron'] });
await fs.copyFile('assets/tray.png', 'dist/tray.png');
const server = await createServer();
await server.listen(); server.printUrls();
const env = { ...process.env, JARVIS_DESKTOP_DEV: '1' };
delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(electron, ['.'], { env, windowsHide: true, stdio: 'inherit' });
child.on('exit', async code => { await server.close(); process.exitCode = code ?? 0; });
child.on('error', async () => { await server.close(); process.exitCode = 1; });
process.on('SIGINT', () => { child.kill(); });
